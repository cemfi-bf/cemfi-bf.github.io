#!/usr/bin/env node
// One-off script: normalizes the scraped CEMFI seminar/workshop archives into a single
// static JS module the app can import. Re-run only if the source scrape files change.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

const MONTHS = {
  january: "01", february: "02", march: "03", april: "04", may: "05", june: "06",
  july: "07", august: "08", september: "09", october: "10", november: "11", december: "12",
  jan: "01", feb: "02", mar: "03", apr: "04", jun: "06", jul: "07", aug: "08",
  sep: "09", oct: "10", nov: "11", dec: "12",
};

function toISO(dateStr) {
  const parts = dateStr.trim().toLowerCase().replace(/\s+/g, " ").split(" ");
  const [day, monthName, year] = parts;
  const month = MONTHS[monthName];
  if (!month) throw new Error(`Unrecognized month in date: "${dateStr}"`);
  return `${year}-${month}-${day.padStart(2, "0")}`;
}

function addMinutes(hhmm, minutes) {
  const [h, m] = hhmm.split(":").map(Number);
  const total = h * 60 + m + minutes;
  const hh = String(Math.floor(total / 60) % 24).padStart(2, "0");
  const mm = String(total % 60).padStart(2, "0");
  return `${hh}:${mm}`;
}

function parseSeminarTime(timeStr) {
  // Seminars only ever have a single start time; default 90 min duration
  // matches the live booking form's default (app.js resetManage: seminar -> 13:30-15:00).
  const startTime = timeStr.trim();
  return { startTime, endTime: addMinutes(startTime, 90) };
}

function parseWorkshopTime(timeStr) {
  // Workshop times are already "HH:MM–HH:MM" (en dash) or "HH:MM-HH:MM".
  const [startTime, endTime] = timeStr.split(/[–-]/).map((s) => s.trim());
  // Default 60 min duration matches the live booking form's workshop default.
  return { startTime, endTime: endTime || addMinutes(startTime, 60) };
}

function stripTrailingPeriodAndSpace(s) {
  return s.replace(/\s+$/, "").replace(/\.$/, "").trim();
}

const seminars = JSON.parse(readFileSync(join(ROOT, "data/cemfi_banking_seminars.json"), "utf8"));
const workshops = JSON.parse(readFileSync(join(ROOT, "data/cemfi_phd_workshops.json"), "utf8"));

const seminarEvents = seminars.map((s) => {
  const { startTime, endTime } = parseSeminarTime(s.time);
  return {
    type: "seminar",
    status: "confirmed",
    presenter: s.speaker || "",
    affiliation: s.affiliation || "",
    title: stripTrailingPeriodAndSpace(s.paper || ""),
    coauthors: "",
    abstract: "",
    date: toISO(s.date),
    startTime,
    endTime,
    source: "archive",
  };
});

const workshopEvents = workshops.map((w) => {
  const { startTime, endTime } = parseWorkshopTime(w.time);
  return {
    type: "workshop",
    status: "confirmed",
    presenter: w.presenter || "",
    affiliation: "",
    title: w.paper && w.paper !== "TBD" ? stripTrailingPeriodAndSpace(w.paper) : "TBD",
    coauthors: "",
    abstract: w.abstract || "",
    date: toISO(w.date),
    startTime,
    endTime,
    source: "archive",
  };
});

const archive = [...seminarEvents, ...workshopEvents].sort(
  (a, b) => a.date.localeCompare(b.date) || a.startTime.localeCompare(b.startTime),
);

const banner = "// Generated by scripts/build-history-archive.mjs — do not hand-edit.\n" +
  "// Source: cemfi_banking_seminars.json (CEMFI B&F seminar series, 2015-2026) and\n" +
  "// cemfi_phd_workshops.json (internal Brown Bag / PhD workshop archive, 2017-2025).\n";

const out = `${banner}export const HISTORY_ARCHIVE = ${JSON.stringify(archive, null, 2)};\n`;

writeFileSync(join(ROOT, "history-archive.js"), out, "utf8");
console.log(`Wrote ${archive.length} archive events to history-archive.js`);
